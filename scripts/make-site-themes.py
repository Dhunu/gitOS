#!/usr/bin/env python3
"""Generates website/themes.js from the app's palettes, so the two can't drift apart."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / "Sources/GitOS/Views/ThemePalettes.swift").read_text()
keys = ["accent", "head", "canvas", "panel", "field", "added", "modified", "removed", "renamed", "conflict"]
hex_color = lambda value: "#" + value.upper()


def gitos(variant):
    block = re.search(r"static let gitOS = ThemePalette\((.*?)\n    \)", source, re.S).group(1)
    return {
        key: hex_color(re.search(key + r": \.init\(light: 0x(\w+), dark: 0x(\w+)\)", block).group(variant))
        for key in keys
    }


themes = [
    {"id": "gitos", "name": "GitOS", "scheme": "dark", **gitos(2)},
    {"id": "gitos-light", "name": "GitOS Light", "scheme": "light", **gitos(1)},
]
pattern = (
    r'make\("([^"]+)", "([^"]+)", \.(dark|light),\s+accent: 0x(\w+), head: 0x(\w+), canvas: 0x(\w+), '
    r"panel: 0x(\w+), field: 0x(\w+),\s+added: 0x(\w+), modified: 0x(\w+), removed: 0x(\w+), "
    r"renamed: 0x(\w+), conflict: 0x(\w+)"
)
for match in re.finditer(pattern, source):
    theme_id, name, scheme, *colors = match.groups()
    themes.append({"id": theme_id, "name": name, "scheme": scheme, **dict(zip(keys, map(hex_color, colors)))})

output = "// Generated by scripts/make-site-themes.py from the app's palettes.\n"
output += "window.GITOS_THEMES = " + json.dumps(themes, indent=1) + ";\n"
(root / "website/themes.js").write_text(output)
print(f"{len(themes)} themes")
